"""文本清洗：把昵称 / 歌名里的表情符号转成可安全写入的纯文字。

为什么需要
----------
网易云的歌单名 / 简介后端是 utf8（3 字节）存储，绝大多数 emoji 是 4 字节字符，
写进去要么整条失败、要么被静默截断——这正是「某些人的昵称带表情时简介写不进去」
的根因。所以入库前必须先把这类字符转掉。

处理规则
--------
1. 认识的 emoji            -> 中文词，如 ``🎵`` -> ``[音符]``
2. 不认识的 4 字节字符      -> 装了 ``emoji`` 库就用库翻译，否则直接丢弃
3. 零宽 / 变体选择符 / 肤色修饰符 / 控制字符 / 私有区字符 -> 一律丢弃
4. 国旗（区域指示符对）     -> ``[旗帜]``
5. ZWJ 组合（👨‍👩‍👧）      -> 只保留首个组件，避免展开成一长串
6. 相邻重复词自动去重，连续空白压成一个空格

使用
----
    sanitize("🌸小仙女🌸")          -> "[樱花]小仙女[樱花]"
    sanitize("🌸小仙女🌸", "strip") -> "小仙女"
    sanitize("🌸小仙女🌸", "keep")  -> "🌸小仙女🌸"
"""

