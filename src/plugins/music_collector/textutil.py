# 别名：有些 emoji 常带变体选择符，剥离后就能命中上表，这里不用额外处理。

# ---------------------------------------------------------------- 正则 / 常量

_ZWJ = "\u200d"
#: ZWJ 组合序列：连接符及其后一个码位整体丢掉，只保留首个组件
_ZWJ_SEQ_RE = re.compile(f"{_ZWJ}[\\s\\S]")
#: 国旗 = 两个区域指示符
_FLAG_RE = re.compile("[\U0001f1e6-\U0001f1ff]{2}")
#: 肤色修饰符
_SKIN_RE = re.compile("[\U0001f3fb-\U0001f3ff]")
#: 变体选择符 / 零宽 / keycap 结合符 / 双向控制符
_INVISIBLE_RE = re.compile("[\ufe00-\ufe0f\u200b-\u200f\u2028-\u202e\u20e3\u2060-\u2064]")
#: 连续空白
_SPACE_RE = re.compile(r"[ \t\u3000]{2,}")
#: 相邻重复的 [词]
_DUP_TOKEN_RE = re.compile(r"(\[[^\[\]]{1,8}\])(\1)+")

#: 判定为「表情类」的码位区间（命中后若无中文词则丢弃）
_EMOJI_RANGES: tuple[tuple[int, int], ...] = (
    (0x1F000, 0x1FAFF),   # 各类 emoji 主区
    (0x1F900, 0x1F9FF),
    (0x2600, 0x27BF),     # 杂项符号 & 装饰符
    (0x2B00, 0x2BFF),
    (0x2300, 0x23FF),     # ⌚⏰⏩ 等
    (0xFE0F, 0xFE0F),
    (0xE000, 0xF8FF),     # 私有区：QQ / 微信自定义表情
)


def _in_emoji_range(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in _EMOJI_RANGES)


# 可选增强：装了 emoji 库就用它翻译表外字符
try:  # pragma: no cover - 取决于运行环境
    import emoji as _emoji_lib
except Exception:  # pragma: no cover
    _emoji_lib = None


def _lib_word(ch: str) -> Optional[str]:
    """借助 emoji 库翻译表外 emoji，失败返回 None。"""
    if _emoji_lib is None:
        return None
    for lang in ("zh", "en"):
        try:
            out = _emoji_lib.demojize(ch, language=lang, delimiters=("", ""))
        except Exception:
            continue
        out = out.strip().strip(":").replace("_", "").replace("-", "")
        if out and out != ch:
            return out[:8]
    return None


# ---------------------------------------------------------------- 对外接口


def has_wide_char(text: str) -> bool:
    """是否含有 4 字节字符（网易云简介写不进去的那种）。"""
    return any(ord(c) > 0xFFFF for c in text or "")


def sanitize(text: str, style: str = "text") -> str:
    """把文本里的表情符号处理掉。

    :param style: ``text`` 转中文词 / ``strip`` 直接删掉 / ``keep`` 原样返回
    """
    if not text:
        return ""
    if style == "keep":
        return text

    # 1. 组合序列先归一
    out = _ZWJ_SEQ_RE.sub("", text)
    out = _SKIN_RE.sub("", out)
    out = _FLAG_RE.sub("[旗帜]" if style == "text" else "", out)
    out = _INVISIBLE_RE.sub("", out)

    # 2. 逐码位转换
    chars: list[str] = []
    for ch in out:
        cp = ord(ch)
        category = unicodedata.category(ch)
        # 控制字符 / 代理对 / 私有区一律丢
        if category in ("Cc", "Cf", "Cs", "Co") and ch not in ("\n", "\r", "\t"):
            continue
        word = _EMOJI_CN.get(ch)
        if word is None and (cp > 0xFFFF or _in_emoji_range(cp)):
            word = _lib_word(ch)
        if word is not None:
            chars.append("" if style == "strip" else f"[{word}]")
            continue
        # 表外的 4 字节字符 / 表情区字符：认不出来就丢，避免写库失败
        if cp > 0xFFFF or (_in_emoji_range(cp) and category == "So"):
            continue
        chars.append(ch)

    result = "".join(chars)
    result = _DUP_TOKEN_RE.sub(r"\1", result)
    result = _SPACE_RE.sub(" ", result)
    return result.strip()


def sanitize_name(text: str, style: str = "text", fallback: str = "") -> str:
    """清洗昵称：清完变空时退回 ``fallback``（通常是 QQ 号）。"""
    cleaned = sanitize(text, style)
    if cleaned:
        return cleaned
    return sanitize(fallback, style) or fallback or "匿名"
